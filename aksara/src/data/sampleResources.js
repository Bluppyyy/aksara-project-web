export const sampleResources = ROWS.map(
  (
    [
      category,
      kode,
      matkul,
      title,
      description,
      prodi,
      semester,
      name,
      angkatan,
      year,
      rating,
      downloads,
      format,
      keywords,
    ],
    i
  ) => ({
    id: `${SAMPLE_PREFIX}${String(i + 1).padStart(2, '0')}`,
    sample: true,
    category,
    thumb: category,
    photo: `foto-${(i % 8) + 1}`, // foto sampul asli (assets/thumbs) dirotasi
    format,
    course: `${kode}  ${matkul}`,
    title,
    description,
    tags: ['FIF', `Semester ${semester}`, PRODI_SHORT[prodi]],
    author: { initials: initialsOf(name), name, meta: `FIF '${angkatan} • ${PRODI_SHORT[prodi]}` },
    fakultas: FIF,
    prodi,
    semester,
    matkul,
    year,
    // Tanggal unggah dibuat menurun supaya urutan "Terbaru" konsisten
    createdAt: new Date(Date.UTC(year, 9 - (i % 10), 28 - (i % 20))).toISOString(),
    rating: rating.toFixed(1),
    downloads,
    keywords,
    bookmarked: false,
  })
);
